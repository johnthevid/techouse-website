/** Run before deployment so edited scripts/styles get fresh browser-cache URLs. */
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const site = resolve(root, 'site');
await writeBuildInfo();
for (const name of ['index.html', 'admin.html']) {
  const file = resolve(site, name);
  const source = await readFile(file, 'utf8');
  const pattern = /((?:src|href)=")(\/?[\w/-]+\.(?:js|css))(?:\?v=[^"]*)?(\")/g;
  const versions = new Map();
  for (const match of source.matchAll(pattern)) {
    const bytes = await readFile(resolve(site, match[2].replace(/^\//, '')));
    versions.set(match[2], createHash('sha256').update(bytes).digest('hex').slice(0, 12));
  }
  const updated = source.replace(
    pattern,
    (_, prefix, asset, suffix) => `${prefix}${asset}?v=${versions.get(asset)}${suffix}`,
  );
  if (updated !== source) await writeFile(file, updated);
}
console.log('Script and stylesheet cache versions match their file contents.');

/**
 * Footer build stamp: branch, version and when the site files last changed.
 * Rewritten only when the branch or the contents of a linked script/stylesheet change.
 */
async function writeBuildInfo() {
  const git = (...args) => {
    try {
      return execFileSync('git', args, { cwd: root, encoding: 'utf8' }).trim();
    } catch {
      return '';
    }
  };
  const branch = git('rev-parse', '--abbrev-ref', 'HEAD') || 'unknown';
  const { version } = JSON.parse(await readFile(resolve(root, 'platform/package.json'), 'utf8'));
  const hash = createHash('sha256').update(branch);
  for (const name of ['index.html', 'admin.html']) {
    const source = await readFile(resolve(site, name), 'utf8');
    for (const [, asset] of source.matchAll(/(?:src|href)="\/?([\w/-]+\.(?:js|css))/g)) {
      if (asset === 'build-info.js') continue;
      hash.update(asset).update(await readFile(resolve(site, asset)));
    }
  }
  const fingerprint = hash.digest('hex').slice(0, 12);
  const file = resolve(site, 'build-info.js');
  const previous = await readFile(file, 'utf8').catch(() => '');
  if (previous.includes(`"fingerprint":"${fingerprint}"`)) return;
  const build = Number(git('rev-list', '--count', 'HEAD') || 0) + 1;
  const info = { branch, version, build, updated: new Date().toISOString(), fingerprint };
  await writeFile(
    file,
    `/** Generated by deployments/techouse-1.0/refresh-assets.mjs. Do not edit. */\nwindow.TechouseBuild = ${JSON.stringify(info)};\n`,
  );
}
